#!/usr/bin/env node
// Assign a stable integer key to every numeric fact in facts/index.json and
// write (a) runtime/fact_keys.json, the append-only id -> key map the runtime
// uses to build the per-worker fact table, and (b) the FACT_* constants block
// in behaviors/host.ts between the markers below. Keys are never reused or
// renumbered: a new fact gets the next free key; a superseded fact keeps its key.
//   node runtime/gen_fact_keys.mjs          (also run by `npm run facts`)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const INDEX = join(ROOT, "facts", "index.json"), KEYS = join(ROOT, "runtime", "fact_keys.json"), HOST = join(ROOT, "behaviors", "host.ts");
const BEGIN = "// ---- facts: generated by runtime/gen_fact_keys.mjs from facts/index.json. Append-only; never edit by hand ----";
const END = "// ---- end of generated facts ----";

export const constName = id => "FACT_" + id.toUpperCase().replace(/[^A-Z0-9]+/g, "_");

export function assignKeys(index, existing = { keys: {}, next: 0 }) {
  const keys = { ...existing.keys }; let next = existing.next;
  // every fact gets a key so fact_tier() works for any record; fact() returns NaN for a table or text value.
  // Scalar facts were keyed first (0..57); later additions of any kind append.
  for (const id of index.ids) { if (typeof index.facts[id].value === "number" && !(id in keys)) keys[id] = next++; }
  for (const id of index.ids) { if (!(id in keys)) keys[id] = next++; }
  return { keys, next };
}

export function hostBlock(index, keys) {
  const lines = [BEGIN, "// fact(key) -> f32 value in the record's unit (NaN for a table or text record); fact_tier(key) -> i32 rank in", "// facts/index.json tier_order (0 defined ... 5 hypothesis), -1 for an unknown key."];
  const byKey = Object.entries(keys.keys).sort((a, b) => a[1] - b[1]);
  for (const [id, key] of byKey) {
    const r = index.facts[id];
    const kind = r && typeof r.value !== "number" ? (Array.isArray(r.value) ? "table; fact() is NaN" : typeof r.value === "object" ? "table; fact() is NaN" : "text; fact() is NaN") : null;
    const label = r ? `${r.label ?? id} [${r.unit}] (${r.tier}${kind ? "; " + kind : ""}${r.superseded_by ? "; superseded by " + r.superseded_by : ""})` : `${id} (no longer in the index)`;
    lines.push(`export const ${constName(id)}: i32 = ${key};`.padEnd(70) + ` // ${label}`);
  }
  lines.push(END);
  return lines.join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes("--check");
  const index = JSON.parse(readFileSync(INDEX, "utf8"));
  const existing = existsSync(KEYS) ? JSON.parse(readFileSync(KEYS, "utf8")) : { keys: {}, next: 0 };
  const keys = assignKeys(index, existing);
  for (const [id, k] of Object.entries(existing.keys)) if (keys.keys[id] !== k) { console.error(`error: key for ${id} changed from ${k} to ${keys.keys[id]}; keys are append-only`); process.exit(1); }
  const keysText = JSON.stringify({ $comment: "id -> integer key for fact(key)/fact_tier(key). Append-only: never reuse or renumber.", ...keys }, null, 1) + "\n";
  let host = readFileSync(HOST, "utf8");
  const block = hostBlock(index, keys);
  const newHost = host.includes(BEGIN) ? host.slice(0, host.indexOf(BEGIN)) + block + host.slice(host.indexOf(END) + END.length) : host.trimEnd() + "\n\n" + block + "\n";
  if (check) {
    const stale = (existsSync(KEYS) ? readFileSync(KEYS, "utf8") : "") !== keysText || host !== newHost;
    if (stale) { console.error("error: runtime/fact_keys.json or the FACT_* block in behaviors/host.ts is stale; run `npm run facts`"); process.exit(1); }
    console.log(`ok: ${Object.keys(keys.keys).length} fact keys current`); process.exit(0);
  }
  writeFileSync(KEYS, keysText);
  writeFileSync(HOST, newHost);
  console.log(`fact keys: ${Object.keys(keys.keys).length} facts, next key ${keys.next}; wrote runtime/fact_keys.json and the FACT_* block in behaviors/host.ts`);
}
